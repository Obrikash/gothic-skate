"""Build the owned x86 bridge and a real worker-protocol smoke test."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

from build_host_probe import PRIVATE, PROJECT, build


RIG = PRIVATE / "host-worker-lab/_derpy_script_loader/scripts/BullyMotion/assets/jimmy-bind.json"


def write_rig_bind(output):
    """rig_bind.h: the worker rig's bind rotations (row-major) and positions, from the lab fixture."""
    bones = json.loads(RIG.read_text())
    if len(bones) != 36:
        raise RuntimeError("The worker rig must have 36 bones")
    rotations = [[bone["matrix"][c][r] for r in range(3) for c in range(3)] for bone in bones]  # columns -> rows
    positions = [bone["matrix"][3] for bone in bones]
    text = ("/* Generated by tools/build_bridge.py from jimmy-bind.json (sha256 "
            + hashlib.sha256(RIG.read_bytes()).hexdigest() + "). */\n#pragma once\n"
            "static const float rig_bind_rot[36][9] = {\n"
            + ",\n".join("{" + ",".join(f"{float(v)!r}f" for v in row) + "}" for row in rotations)
            + "};\nstatic const float rig_bind_pos[36][3] = {\n"
            + ",\n".join("{" + ",".join(f"{float(v)!r}f" for v in row) + "}" for row in positions) + "};\n")
    (output / "rig_bind.h").write_text(text)


def main(smoke_only=False):
    build()
    output = PRIVATE / "build"
    write_rig_bind(output)
    zig = PRIVATE / "toolchain/zig-x86_64-windows-0.17.0/zig.exe"
    environment = os.environ.copy()
    environment["ZIG_GLOBAL_CACHE_DIR"] = str(PRIVATE / "compiler-cache/global")
    environment["ZIG_LOCAL_CACHE_DIR"] = str(PRIVATE / "compiler-cache/local")
    targets = [("worker-smoke.exe", ["worker_smoke.c"], [])]
    if not smoke_only:
        targets.append(("ArcholosSkateBridge.dll", ["host_bridge.c", "capture_core.c", "retarget_core.c"], ["-shared"]))
    for name, sources, flags in targets:
        target = output / name
        command = [str(zig), "cc", "-target", "x86-windows-gnu", "-O2", "-Wall", "-Wextra", *flags,
                   "-I", str(output), *(str(PROJECT / "native" / source) for source in sources), str(PROJECT / "native/worker_client.c"),
                   "-luser32", "-lkernel32", "-o", str(target)]
        subprocess.run(command, env=environment, cwd=output, check=True)
        report = {"path": str(target), "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
                  "mechanism": "union-callbacks-movement-v1" if flags else "x86-worker-protocol-smoke",
                  "gameplayVerified": False}
        (output / (name + ".json")).write_text(json.dumps(report, indent=2))
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--smoke-only", action="store_true")
    main(parser.parse_args().smoke_only)
